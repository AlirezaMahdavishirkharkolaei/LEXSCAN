// Export an analysis as a self-contained HTML report or Markdown.

const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
const VER = { exact: "verified in document", approximate: "approximately verified", not_found: "NOT found in document" };

export function toMarkdown({ docName, analysis: a, scan, options }) {
  const L = [];
  L.push(`# Contract review: ${docName}`, "");
  L.push(`*Generated by LexScan on ${new Date().toISOString().slice(0, 10)} · framework: ${options.jurisdictionLabel} · perspective: ${options.perspective || "neutral"}*`, "");
  if (a) {
    L.push(`**Overall risk: ${a.overall_risk}** (confidence ${a.confidence})`, "", a.summary, "", `*Why:* ${a.risk_rationale}`, "");
    if (a.verification_summary?.checked) L.push(`Quotes verified against the document: ${a.verification_summary.verified}/${a.verification_summary.checked}`, "");
    if (a.parties?.length) L.push("## Parties", ...a.parties.map((p) => `- ${p.name} — ${p.role}`), "");
    if (a.key_terms?.length) L.push("## Key terms", ...a.key_terms.map((k) => `- **${k.label}:** ${k.value}`), "");
    L.push("## Clause review");
    for (const c of a.clauses || []) {
      L.push("", `### ${c.title} — ${c.risk} risk (favours ${c.favours})`);
      if (c.quote) L.push(`> ${c.quote}${c.paragraph ? ` [P${c.paragraph}]` : ""} — *${VER[c.verification?.status] || ""}*`);
      L.push("", c.assessment, "", `**Recommendation:** ${c.recommendation}`);
      if (c.legal_reference) L.push(`*Reference:* ${c.legal_reference}`);
    }
    if (a.red_flags?.length) L.push("", "## Red flags", ...a.red_flags.map((f) => `- **${f.issue}** (${f.severity}): ${f.why}${f.quote ? ` — “${f.quote}”` : ""}`));
    if (a.missing_clauses?.length) L.push("", "## Missing clauses", ...a.missing_clauses.map((m) => `- **${m.clause}:** ${m.why_it_matters}`));
    if (a.negotiation_points?.length) L.push("", "## Negotiation points", ...a.negotiation_points.map((n) => `- ${n}`));
    if (a.questions_for_client?.length) L.push("", "## Questions for the client", ...a.questions_for_client.map((n) => `- ${n}`));
    if (a.jurisdiction_notes?.length) L.push("", "## Jurisdiction notes", ...a.jurisdiction_notes.map((n) => `- ${n.note}${n.reference ? ` (${n.reference})` : ""} — confidence ${n.confidence}`));
  }
  if (scan) {
    L.push("", "## Instant scan", `- Clauses found: ${scan.clauses.filter((c) => c.present).map((c) => c.label).join(", ")}`);
    if (scan.missing.length) L.push(`- Standard clauses not found: ${scan.missing.join(", ")}`);
    scan.redFlags.forEach((f) => L.push(`- [P${f.paragraph + 1}] ${f.text}`));
  }
  L.push("", "---", "*This report supports, and does not replace, review by a qualified lawyer.*");
  return L.join("\n");
}

export function toHtml(ctx) {
  const { docName, analysis: a, scan, options } = ctx;
  const risk = (r) => `<span class="pill ${esc(r)}">${esc(r)}</span>`;
  const sec = (title, body) => (body ? `<h2>${esc(title)}</h2>${body}` : "");
  const list = (items) => (items?.length ? `<ul>${items.map((i) => `<li>${i}</li>`).join("")}</ul>` : "");
  const clauses = (a?.clauses || []).map((c) => `<div class="clause ${esc(c.risk)}"><h3>${esc(c.title)} ${risk(c.risk)}</h3>
    <p class="meta">${esc(c.type)} · favours ${esc(c.favours)}${c.paragraph ? ` · P${c.paragraph}` : ""}</p>
    ${c.quote ? `<blockquote dir="auto">${esc(c.quote)}<span class="ver ${esc(c.verification?.status)}">${esc(VER[c.verification?.status] || "")}</span></blockquote>` : ""}
    <p dir="auto">${esc(c.assessment)}</p><p dir="auto"><b>Recommendation:</b> ${esc(c.recommendation)}</p>
    ${c.legal_reference ? `<p class="meta">Reference: ${esc(c.legal_reference)}</p>` : ""}</div>`).join("");
  return `<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Contract review: ${esc(docName)}</title><style>
body{font:15px/1.6 Georgia,serif;color:#15201d;max-width:860px;margin:0 auto;padding:32px 20px 60px;background:#fff}
h1{font-size:26px;margin:0 0 4px}h2{font:600 18px system-ui,sans-serif;margin:28px 0 8px;border-bottom:1px solid #dbe1de;padding-bottom:4px}
h3{font:600 15px system-ui,sans-serif;margin:0 0 4px}.meta{color:#5b6763;font:13px system-ui,sans-serif}
.box{border:1px solid #dbe1de;border-left:5px solid #b3261e;border-radius:8px;padding:12px 16px}
.clause{border:1px solid #dbe1de;border-left:4px solid #999;border-radius:8px;padding:10px 14px;margin:10px 0;break-inside:avoid}
.clause.high{border-left-color:#b3261e}.clause.medium{border-left-color:#8a5600}.clause.low{border-left-color:#1e6f3f}
.pill{font:700 11px system-ui,sans-serif;border-radius:99px;padding:1px 8px;text-transform:uppercase;vertical-align:2px}
.pill.high{background:#fbe4e2;color:#b3261e}.pill.medium{background:#fcefd2;color:#8a5600}.pill.low{background:#e1f2e7;color:#1e6f3f}
blockquote{margin:6px 0;padding:6px 10px;border-left:3px solid #4a8fd4;background:#eef6ff}
.ver{display:block;font:600 11.5px system-ui,sans-serif;margin-top:3px}.ver.exact{color:#1e6f3f}.ver.approximate{color:#8a5600}.ver.not_found{color:#b3261e}
footer{margin-top:36px;color:#5b6763;font:12.5px system-ui,sans-serif;border-top:1px solid #dbe1de;padding-top:10px}
</style></head><body>
<h1>Contract review: ${esc(docName)}</h1>
<p class="meta">LexScan · ${new Date().toISOString().slice(0, 10)} · ${esc(options.jurisdictionLabel)} · perspective: ${esc(options.perspective || "neutral")}</p>
${a ? `<div class="box"><b>Overall risk: ${esc(a.overall_risk)}</b> · confidence ${esc(a.confidence)}${a.verification_summary?.checked ? ` · ${a.verification_summary.verified}/${a.verification_summary.checked} quotes verified` : ""}
<p dir="auto">${esc(a.summary)}</p><p class="meta" dir="auto">${esc(a.risk_rationale)}</p></div>` : ""}
${sec("Key terms", list((a?.key_terms || []).map((k) => `<b>${esc(k.label)}:</b> ${esc(k.value)}`)))}
${sec("Clause review", clauses)}
${sec("Red flags", list((a?.red_flags || []).map((f) => `<b>${esc(f.issue)}</b> ${risk(f.severity)} ${esc(f.why)}`)))}
${sec("Missing clauses", list((a?.missing_clauses || []).map((m) => `<b>${esc(m.clause)}:</b> ${esc(m.why_it_matters)}`)))}
${sec("Negotiation points", list((a?.negotiation_points || []).map(esc)))}
${sec("Questions for the client", list((a?.questions_for_client || []).map(esc)))}
${sec("Jurisdiction notes", list((a?.jurisdiction_notes || []).map((n) => `${esc(n.note)}${n.reference ? ` <span class="meta">(${esc(n.reference)})</span>` : ""} <span class="meta">confidence ${esc(n.confidence)}</span>`)))}
${scan ? sec("Instant scan (rule-based)", list([
    `Clauses found: ${esc(scan.clauses.filter((c) => c.present).map((c) => c.label).join(", "))}`,
    ...(scan.missing.length ? [`Standard clauses not found: ${esc(scan.missing.join(", "))}`] : []),
    ...scan.redFlags.map((f) => `P${f.paragraph + 1}: ${esc(f.text)}`)])) : ""}
<footer>This report supports, and does not replace, review by a qualified lawyer. Quotes marked “NOT found in document” were not located in the source text and must be checked.</footer>
</body></html>`;
}
